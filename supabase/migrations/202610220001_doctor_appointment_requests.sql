-- Appointment request storage for the Dr. M. Kalaivanan website.
-- Public visitors can INSERT requests, but cannot read patient records.
create table if not exists public.doctor_appointment_requests (
  id bigint generated by default as identity primary key,
  patient_name text not null check (char_length(patient_name) between 2 and 100),
  phone text not null check (char_length(phone) between 5 and 20),
  email text,
  treatment text not null,
  preferred_date date not null,
  preferred_time text,
  message text,
  status text not null default 'pending' check (status in ('pending', 'contacted', 'confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);

alter table public.doctor_appointment_requests enable row level security;

revoke all on table public.doctor_appointment_requests from anon, authenticated;
grant insert on table public.doctor_appointment_requests to anon;
grant insert on table public.doctor_appointment_requests to authenticated;

drop policy if exists "Public can submit appointment requests" on public.doctor_appointment_requests;
create policy "Public can submit appointment requests"
  on public.doctor_appointment_requests
  for insert
  to anon, authenticated
  with check (
    char_length(patient_name) between 2 and 100
    and char_length(phone) between 5 and 20
    and preferred_date >= current_date
  );

